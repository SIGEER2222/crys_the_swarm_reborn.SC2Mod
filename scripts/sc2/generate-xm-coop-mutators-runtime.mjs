function read(filePath) {
  return fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : "";
}

function write(filePath, text) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, text, "utf8");
}

function parseMutatorIds() {
  const userData = read(path.join(targetGameData, "UserData.xml"));
  const match = userData.match(/<CUser id="Mutators">([\s\S]*?)<\/CUser>/);
  if (!match) {
    throw new Error("CUser id=\"Mutators\" block not found in target UserData.xml");
  }

  return [...match[1].matchAll(/<Instances Id="([^"]+)">/g)]
    .map((match) => match[1])
    .filter((id) => id !== "[Default]" && id !== "Random");
}

function parseOfficialRegistrations() {
  const lib = read(path.join(officialBase, "libcomu.galaxy"));
  const registrations = new Map();
  const pattern = /libCOMU_gf_CT_RegisterMutator\("([^"]+)",\s*libCOMU_gt_([^,\s]+),\s*libCOMU_gt_([^)]+)\);/g;
  for (const match of lib.matchAll(pattern)) {
    registrations.set(match[1], {
      officialInit: match[2],
      officialShutdown: match[3],
    });
  }
  return registrations;
}

function collectOfficialCatalogNodes() {
  const result = new Map();
  const officialGameData = path.join(officialBase, "gamedata");

  for (const fileName of catalogFiles) {
    const source = path.join(officialGameData, fileName.toLowerCase());
    const xml = read(source).replace(/<!--[\s\S]*?-->/g, "");
    if (!xml) {
      continue;
    }

    const nodes = [];
    const pattern = /<([A-Za-z0-9_]+)\b[^>]*(?:id|default)="([^"]+)"[\s\S]*?<\/\1>/g;
    for (const match of xml.matchAll(pattern)) {
      const node = match[0];
      const id = match[2];
      if (node.includes("Mutator") || id.includes("Mutator") || plagues.has(id)) {
        nodes.push(node);
      }
    }

    if (nodes.length > 0) {
      result.set(fileName, nodes);
    }
  }

  return result;
}

function generateRuntime(mutators, registrations) {
  const triggerNames = new Map();
  for (const mutator of mutators) {
    const safe = mutator.replace(/[^A-Za-z0-9_]/g, "_");
    triggerNames.set(mutator, {
      init: `libXMCM_gt_Initialize_${safe}`,
      shutdown: `libXMCM_gt_Shutdown_${safe}`,
      initFunc: `libXMCM_gt_Initialize_${safe}_Func`,
      shutdownFunc: `libXMCM_gt_Shutdown_${safe}_Func`,
      initInit: `libXMCM_gt_Initialize_${safe}_Init`,
      shutdownInit: `libXMCM_gt_Shutdown_${safe}_Init`,
    });
  }

  const header = [
    'include "TriggerLibs/natives"',
    "",
    "//--------------------------------------------------------------------------------------------------",
    "// Library: XMCoopMutators",
    "// Generated by scripts/sc2/generate-xm-coop-mutators-runtime.mjs.",
    "//--------------------------------------------------------------------------------------------------",
    "const int libXMCM_gv_mutatorQuickPlague = 18;",
    "",
    "bool libXMCM_gv_mutatorQuickList[128];",
    "int libXMCM_gv_mutatorEnabledCount;",
    "",
    ...mutators.flatMap((mutator) => {
      const names = triggerNames.get(mutator);
      return [`trigger ${names.init};`, `trigger ${names.shutdown};`];
    }),
    "trigger libXMCM_gt_PlagueDeath;",
    "trigger libXMCM_gt_UnitCreation;",
    "",
    "bool libXMCM_gf_MutatorIsEnabled (string lp_mutator);",
    "void libXMCM_gf_EnableDisableMutator (bool lp_enableDisable, string lp_mutator);",
    "void libXMCM_gf_EnableMutator (string lp_mutator);",
    "void libXMCM_gf_DisableMutator (string lp_mutator);",
    "void libXMCM_gf_EnableAllMutators ();",
    "void libXMCM_gf_DisableAllMutators ();",
    "int libXMCM_gf_MutatorEnabledCount ();",
    "trigger libXMCM_gf_MutatorInitTrigger (string lp_mutator);",
    "trigger libXMCM_gf_MutatorShutdownTrigger (string lp_mutator);",
    "void libXMCM_gf_RegisterMutator (string lp_mutator, trigger lp_initTrigger, trigger lp_shutdownTrigger);",
    "void libXMCM_gf_RegisterDefaultMutators ();",
    "void libXMCM_gf_ApplyPlague (unit lp_newUnit);",
    "void libXMCM_gf_ApplyPlagueOnDeath (unit lp_killedUnit);",
    "",
    "void libXMCM_InitLib ();",
    "",
  ].join("\n");

  const initCases = mutators.flatMap((mutator) => {
    const names = triggerNames.get(mutator);
    if (mutator === "Plague") {
      return [
        `bool ${names.initFunc} (bool testConds, bool runActions) {`,
        "    if (!runActions) { return true; }",
        "    libXMCM_gv_mutatorQuickList[libXMCM_gv_mutatorQuickPlague] = true;",
        "    TriggerEnable(libXMCM_gt_PlagueDeath, true);",
        "    return true;",
        "}",
        "",
        `bool ${names.shutdownFunc} (bool testConds, bool runActions) {`,
        "    unitgroup lv_allUnits;",
        "    unit lv_indexUnit;",
        "    if (!runActions) { return true; }",
        "    libXMCM_gv_mutatorQuickList[libXMCM_gv_mutatorQuickPlague] = false;",
        "    TriggerEnable(libXMCM_gt_PlagueDeath, false);",
        "    lv_allUnits = UnitGroup(null, c_playerAny, RegionEntireMap(), null, 0);",
        "    lv_indexUnit = UnitGroupUnit(lv_allUnits, 1);",
        "    while (lv_indexUnit != null) {",
        '        UnitBehaviorRemove(lv_indexUnit, "MutatorPlagueBehavior", c_unitBehaviorCountAll);',
        '        UnitBehaviorRemove(lv_indexUnit, "MutatorPlagueBehaviorVisual", c_unitBehaviorCountAll);',
        "        UnitGroupRemove(lv_allUnits, lv_indexUnit);",
        "        lv_indexUnit = UnitGroupUnit(lv_allUnits, 1);",
        "    }",
        "    return true;",
        "}",
        "",
      ];
    }

    return [
      `bool ${names.initFunc} (bool testConds, bool runActions) { if (runActions) { DataTableSetBool(true, "XMCM_ENABLED_${mutator}", true); } return true; }`,
      `bool ${names.shutdownFunc} (bool testConds, bool runActions) { if (runActions) { DataTableSetBool(true, "XMCM_ENABLED_${mutator}", false); } return true; }`,
      "",
    ];
  });

  const runtime = [
    'include "TriggerLibs/NativeLib"',
    "",
    'include "LibXMCoopMutators_h"',
    "",
    "//--------------------------------------------------------------------------------------------------",
    "// Library: XMCoopMutators",
    "// Generated by scripts/sc2/generate-xm-coop-mutators-runtime.mjs.",
    "//--------------------------------------------------------------------------------------------------",
    "void libXMCM_InitLibraries () {",
    "    libNtve_InitVariables();",
    "}",
    "",
    "bool libXMCM_gf_MutatorIsEnabled (string lp_mutator) {",
    '    return (UserDataGetInt("Mutators", lp_mutator, "State", 1) == 1);',
    "}",
    "",
    "trigger libXMCM_gf_MutatorInitTrigger (string lp_mutator) {",
    '    return DataTableGetTrigger(true, ("XMCM_IN_" + lp_mutator));',
    "}",
    "",
    "trigger libXMCM_gf_MutatorShutdownTrigger (string lp_mutator) {",
    '    return DataTableGetTrigger(true, ("XMCM_SD_" + lp_mutator));',
    "}",
    "",
    "void libXMCM_gf_RegisterMutator (string lp_mutator, trigger lp_initTrigger, trigger lp_shutdownTrigger) {",
    '    DataTableSetTrigger(true, ("XMCM_IN_" + lp_mutator), lp_initTrigger);',
    '    DataTableSetTrigger(true, ("XMCM_SD_" + lp_mutator), lp_shutdownTrigger);',
    "}",
    "",
    "void libXMCM_gf_EnableDisableMutator (bool lp_enableDisable, string lp_mutator) {",
    "    trigger lv_mutatorTrigger;",
    "    int lv_state;",
    "    if (lp_enableDisable) {",
    "        if (!libXMCM_gf_MutatorIsEnabled(lp_mutator)) { libXMCM_gv_mutatorEnabledCount += 1; }",
    "        lv_mutatorTrigger = libXMCM_gf_MutatorInitTrigger(lp_mutator);",
    "        if (lv_mutatorTrigger != null) { TriggerExecute(lv_mutatorTrigger, true, true); }",
    "        lv_state = 1;",
    "    }",
    "    else {",
    "        if (libXMCM_gf_MutatorIsEnabled(lp_mutator)) { libXMCM_gv_mutatorEnabledCount -= 1; }",
    "        lv_mutatorTrigger = libXMCM_gf_MutatorShutdownTrigger(lp_mutator);",
    "        if (lv_mutatorTrigger != null) { TriggerExecute(lv_mutatorTrigger, true, true); }",
    "        lv_state = 0;",
    "    }",
    '    UserDataSetInt("Mutators", lp_mutator, "State", 1, lv_state);',
    "}",
    "",
    "void libXMCM_gf_EnableMutator (string lp_mutator) { libXMCM_gf_EnableDisableMutator(true, lp_mutator); }",
    "void libXMCM_gf_DisableMutator (string lp_mutator) { libXMCM_gf_EnableDisableMutator(false, lp_mutator); }",
    "",
    "void libXMCM_gf_EnableAllMutators () {",
    ...mutators.map((mutator) => `    libXMCM_gf_EnableMutator("${mutator}");`),
    "}",
    "",
    "void libXMCM_gf_DisableAllMutators () {",
    ...[...mutators].reverse().map((mutator) => `    libXMCM_gf_DisableMutator("${mutator}");`),
    "}",
    "",
    "int libXMCM_gf_MutatorEnabledCount () { return libXMCM_gv_mutatorEnabledCount; }",
    "",
    "void libXMCM_gf_RegisterDefaultMutators () {",
    ...mutators.map((mutator) => {
      const names = triggerNames.get(mutator);
      const reg = registrations.get(mutator);
      const comment = reg ? ` // official: ${reg.officialInit} / ${reg.officialShutdown}` : "";
      return `    libXMCM_gf_RegisterMutator("${mutator}", ${names.init}, ${names.shutdown});${comment}`;
    }),
    "}",
    "",
    "bool libXMCM_gf_UnitIsPlagueCandidate (unit lp_unit) {",
    "    string lv_unitType;",
    "    if (lp_unit == null) { return false; }",
    "    lv_unitType = UnitGetType(lp_unit);",
    '    if ((UnitGetOwner(lp_unit) == c_playerAny) || (lv_unitType == "AdeptPhaseShift") || (lv_unitType == "DisruptorPhased") || (lv_unitType == "BiomassPickup") || (lv_unitType == "Larva")) { return false; }',
    "    if (UnitFilterMatch(lp_unit, 1, UnitFilter(0, 0, (1 << c_targetFilterPlayer) | (1 << c_targetFilterAlly) | (1 << c_targetFilterNeutral) | (1 << c_targetFilterStructure) | (1 << c_targetFilterMissile), (1 << (c_targetFilterInvulnerable - 32)))) == false) { return false; }",
    "    return PlayerGroupHasPlayer(PlayerGroupAlliance(c_playerGroupEnemy, 1), UnitGetOwner(lp_unit));",
    "}",
    "",
    "void libXMCM_gf_ApplyPlague (unit lp_newUnit) {",
    '    if ((!libXMCM_gv_mutatorQuickList[libXMCM_gv_mutatorQuickPlague]) || (!libXMCM_gf_MutatorIsEnabled("Plague")) || (!libXMCM_gf_UnitIsPlagueCandidate(lp_newUnit))) { return; }',
    '    if (RandomInt(1, 10) == 1) { UnitBehaviorAdd(lp_newUnit, "MutatorPlagueBehaviorVisual", lp_newUnit, 1); }',
    "}",
    "",
    "void libXMCM_gf_ApplyPlagueOnDeath (unit lp_killedUnit) {",
    "    unitgroup lv_nearbyUnits;",
    "    unit lv_indexUnit;",
    "    if ((!libXMCM_gv_mutatorQuickList[libXMCM_gv_mutatorQuickPlague]) || (lp_killedUnit == null)) { return; }",
    '    if ((UnitHasBehavior2(lp_killedUnit, "MutatorPlagueBehavior") == false) && (UnitHasBehavior2(lp_killedUnit, "MutatorPlagueBehaviorVisual") == false)) { return; }',
    "    lv_nearbyUnits = UnitGroup(null, c_playerAny, RegionCircle(UnitGetPosition(lp_killedUnit), 4.0), UnitFilter(0, 0, (1 << c_targetFilterStructure) | (1 << c_targetFilterMissile), (1 << (c_targetFilterDead - 32)) | (1 << (c_targetFilterInvulnerable - 32))), 0);",
    "    lv_indexUnit = UnitGroupUnit(lv_nearbyUnits, 1);",
    "    while (lv_indexUnit != null) {",
    '        if ((UnitHasBehavior2(lv_indexUnit, "MutatorPlagueBehavior") == false) && libXMCM_gf_UnitIsPlagueCandidate(lv_indexUnit)) { UnitBehaviorAdd(lv_indexUnit, "MutatorPlagueBehavior", lv_indexUnit, 1); }',
    "        UnitGroupRemove(lv_nearbyUnits, lv_indexUnit);",
    "        lv_indexUnit = UnitGroupUnit(lv_nearbyUnits, 1);",
    "    }",
    '    UnitBehaviorRemove(lp_killedUnit, "MutatorPlagueBehavior", c_unitBehaviorCountAll);',
    '    UnitBehaviorRemove(lp_killedUnit, "MutatorPlagueBehaviorVisual", c_unitBehaviorCountAll);',
    "}",
    "",
    ...initCases,
    "bool libXMCM_gt_PlagueDeath_Func (bool testConds, bool runActions) {",
    "    if (!runActions) { return true; }",
    "    libXMCM_gf_ApplyPlagueOnDeath(EventUnit());",
    "    return true;",
    "}",
    "",
    "bool libXMCM_gt_UnitCreation_Func (bool testConds, bool runActions) {",
    "    if (!runActions) { return true; }",
    "    libXMCM_gf_ApplyPlague(EventUnitCreatedUnit());",
    "    return true;",
    "}",
    "",
    ...mutators.flatMap((mutator) => {
      const names = triggerNames.get(mutator);
      return [
        `void ${names.initInit} () { ${names.init} = TriggerCreate("${names.initFunc}"); }`,
        `void ${names.shutdownInit} () { ${names.shutdown} = TriggerCreate("${names.shutdownFunc}"); }`,
      ];
    }),
    "",
    "void libXMCM_gt_PlagueDeath_Init () {",
    '    libXMCM_gt_PlagueDeath = TriggerCreate("libXMCM_gt_PlagueDeath_Func");',
    "    TriggerEnable(libXMCM_gt_PlagueDeath, false);",
    "    TriggerAddEventUnitDied(libXMCM_gt_PlagueDeath, null);",
    "}",
    "",
    "void libXMCM_gt_UnitCreation_Init () {",
    '    libXMCM_gt_UnitCreation = TriggerCreate("libXMCM_gt_UnitCreation_Func");',
    "    TriggerAddEventUnitCreated(libXMCM_gt_UnitCreation, null, null, null);",
    "}",
    "",
    "void libXMCM_InitTriggers () {",
    ...mutators.flatMap((mutator) => {
      const names = triggerNames.get(mutator);
      return [`    ${names.initInit}();`, `    ${names.shutdownInit}();`];
    }),
    "    libXMCM_gt_PlagueDeath_Init();",
    "    libXMCM_gt_UnitCreation_Init();",
    "}",
    "",
    "void libXMCM_InitLib () {",
    "    libXMCM_InitLibraries();",
    "    libXMCM_InitTriggers();",
    "    libXMCM_gf_RegisterDefaultMutators();",
    "}",
    "",
  ].join("\n");

  return { header, runtime };
}

function writeCatalog(nodesByFile) {
  const includePaths = [
    "GameData/UserData.xml",
    ...[...nodesByFile.keys()].map((file) => `GameData/${file}`),
  ];

  write(
    path.join(targetBase, "GameData.xml"),
    [
      '<?xml version="1.0" encoding="utf-8"?>',
      "<Includes>",
      ...includePaths.map((includePath) => `    <Catalog path="${includePath}"/>`),
      "</Includes>",
      "",
    ].join("\n")
  );

  for (const [fileName, nodes] of nodesByFile) {
    write(
      path.join(targetGameData, fileName),
      [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<Catalog>",
        `    <!-- Official StarCraft II co-op mutator Catalog nodes imported from ${fileName.toLowerCase()}. -->`,
        ...nodes.map((node) =>
          node
            .split(/\r?\n/)
            .map((line) => `    ${line}`)
            .join("\n")
        ),
        "</Catalog>",
        "",
      ].join("\n")
    );
  }
}

function main() {
  const mutators = parseMutatorIds();
  const registrations = parseOfficialRegistrations();
  const catalogNodes = collectOfficialCatalogNodes();
  const { header, runtime } = generateRuntime(mutators, registrations);

  write(path.join(targetBase, "LibXMCoopMutators_h.galaxy"), header);
  write(path.join(targetBase, "LibXMCoopMutators.galaxy"), runtime);
  writeCatalog(catalogNodes);

  const missingRegistrations = mutators.filter((mutator) => !registrations.has(mutator));
  const summary = {
    mutatorCount: mutators.length,
    officialRegistrationCount: registrations.size,
    missingRegistrations,
    catalogFiles: [...catalogNodes.entries()].map(([fileName, nodes]) => ({
      fileName,
      nodeCount: nodes.length,
    })),
    runtimeLines: runtime.split(/\r?\n/).length,
    headerLines: header.split(/\r?\n/).length,
  };

  console.log(JSON.stringify(summary, null, 2));
}

main();
