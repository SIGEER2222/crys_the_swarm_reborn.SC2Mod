function unique(values) {
  return [...new Set(values.filter(Boolean))];
}

function unitIdsFrom(file) {
  return readJson(file).map((entry) => entry.unit_id).filter(Boolean);
}

function resolveAlias(commander, id, aliases) {
  return aliases[commander]?.[id] ?? id;
}

function finishGalaxy(lines) {
  return `${lines.join("\n").replace(/\n+$/u, "")}\n`;
}

function lineCreateUnit(commander, id, index, rosterKind, createFn, aliases) {
  const resolved = resolveAlias(commander, id, aliases);
  if (resolved !== id) {
    return `    ${createFn}Alias(lp_player, "${id}", "${resolved}", ${index}, ${rosterKind});`;
  }
  return `    ${createFn}(lp_player, "${id}", ${index}, ${rosterKind});`;
}

