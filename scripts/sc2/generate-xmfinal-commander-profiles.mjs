function rawAbilityIdFrom(abilCmd) {
  if (!abilCmd || abilCmd === "255,255") {
    return "";
  }
  const abilityId = abilCmd.split(",")[0].trim();
  return abilityId || "";
}

function abilityIdFrom(abilCmd) {
  const abilityId = rawAbilityIdFrom(abilCmd);
  if (!abilityId || ignoredAbilities.has(abilityId)) {
    return "";
  }
  return abilityId;
}

function isIgnoredButton(button) {
  const face = button.face || "";
  const rawAbilityId = rawAbilityIdFrom(button.abil_cmd || "");
  const abilityId = abilityIdFrom(button.abil_cmd || "");
  if (ignoredFaces.has(face) || ignoredAbilities.has(rawAbilityId)) {
    return true;
  }
  if (!face && !abilityId && !(button.requirements || "")) {
    return true;
  }
  return false;
}

function matchesAny(values, value) {
  return Array.isArray(values) && values.includes(value);
}

function isMisattributedCommanderButton(commander, unitId, button) {
  const face = String(button.face ?? "");
  const abilityId = rawAbilityIdFrom(button.abil_cmd || "");
  const requirementId = String(button.requirements ?? "");
  return misattributedCommanderAbilityFilters.some((filter) =>
    filter.commander === commander
    && filter.unitId === unitId
    && (
      matchesAny(filter.faceIds, face)
      || matchesAny(filter.abilityIds, abilityId)
      || matchesAny(filter.requirementIds, requirementId)
    ));
}

function entryKind(button, abilityId) {
  const type = button.type || "";
  const face = button.face || "";
  if (type === "Passive") {
    return "passive";
  }
  if (/Morph|Evolve|Burrow|Siege|Unsiege/i.test(`${face} ${abilityId}`)) {
    return "evolution";
  }
  return "ability";
}

function overrideAbilityRow(commander, sourceObjectId, row) {
  const override = abilityRowOverrides[commander]?.[sourceObjectId]?.[row.buttonId]
    ?? abilityRowOverrides[commander]?.[sourceObjectId]?.[row.abilityId];
  if (!override) {
    return row;
  }
  return {
    ...row,
    buttonId: override.buttonId ?? row.buttonId,
    abilityId: override.abilityId ?? row.abilityId,
    requirementId: override.requirementId ?? row.requirementId,
    kind: override.kind ?? row.kind,
  };
}

function abilityRowsForObject(commander, object) {
  const manual = manualAbilityObjects[commander]?.[object.unit_id];
  if (manual) {
    return manual.map(([objectId, buttonId, abilityId, requirementId, kind]) =>
      overrideAbilityRow(commander, object.unit_id, { objectId, buttonId, abilityId, requirementId, kind }),
    );
  }

  const rows = [];
  const objectId = resolveAlias(commander, object.unit_id, abilityObjectAliases);
  for (const card of object.cards ?? []) {
    for (const button of card.buttons ?? []) {
      if (isIgnoredButton(button) || isMisattributedCommanderButton(commander, object.unit_id, button)) {
        continue;
      }
      const buttonId = button.face || "";
      const type = button.type || "";
      const abilityId = type === "Passive" ? "" : abilityIdFrom(button.abil_cmd || "");
      const requirementId = button.requirements || "";
      if (!buttonId && !abilityId && !requirementId) {
        continue;
      }
      rows.push(overrideAbilityRow(commander, object.unit_id, { objectId, buttonId, abilityId, requirementId, kind: entryKind(button, abilityId) }));
    }
  }

  if (rows.length === 0 && object.unit_id) {
    rows.push({ objectId, buttonId: "", abilityId: "", requirementId: "", kind: "unit_card_no_specials" });
  }
  return rows;
}

function commandCardObjects(commander, objectType) {
  const objects = readJson(path.join(commanderDir(commander), "command_cards.json"))
    .filter((entry) => entry.object_type === objectType && entry.unit_id);
  const seen = new Set();
  const result = [];
  for (const object of objects) {
    if (seen.has(object.unit_id)) {
      continue;
    }
    seen.add(object.unit_id);
    result.push(object);
  }
  return result;
}

function abilityRows(commander, objectType) {
  const result = [];
  const seen = new Set();
  for (const object of commandCardObjects(commander, objectType)) {
    for (const row of abilityRowsForObject(commander, object)) {
      const key = [row.objectId, row.buttonId, row.abilityId, row.requirementId, row.kind].join("\t");
      if (seen.has(key)) {
        continue;
      }
      seen.add(key);
      result.push(row);
    }
  }
  return result;
}

function renderAbilityFile(commanders, objectType) {
  const isHero = objectType === "Hero";
  const title = isHero ? "hero" : "unit";
  const suffix = isHero ? "HeroAbilities" : "UnitAbilities";
  const sourceType = isHero ? "Hero" : "Unit";
  const lines = [
    `// XMFinal split module: official commander ${title} ability smoke profiles.`,
    "// Source authority: commanders/<Commander>/command_cards.json.",
    generatedBy,
    "",
  ];

  for (const commander of commanders) {
    const rows = abilityRows(commander, sourceType);
    const fn = functionCommander(commander);
    lines.push(`bool libE0EAE146_gf_XMTestBench_${fn}${suffix} (int lp_player, string lp_scenarioKind) {`);
    if (isHero) {
      lines.push('    if (lp_scenarioKind != "hero_ability_smoke") {');
    } else {
      lines.push('    if (lp_scenarioKind != "unit_ability_smoke" && lp_scenarioKind != "unit_evolution_smoke") {');
    }
    lines.push("        return false;");
    lines.push("    }");
    if (rows.length === 0) {
      lines.push(`    libE0EAE146_gf_XMDbgLog("INFO", "TEST_COMMANDER_ABILITIES_EMPTY", "commander=${commander} scenario=" + lp_scenarioKind + " expected=0 source=command_cards_json");`);
    }
    rows.forEach((row) => {
      lines.push(`    libE0EAE146_gf_XMTestBench_CheckAbilityProfileEntry(lp_player, "${commander}", lp_scenarioKind, "${row.objectId}", "${row.buttonId}", "${row.abilityId}", "${row.requirementId}", "${row.kind}");`);
    });
    lines.push(`    libE0EAE146_gf_XMTestBench_LogAbilityProfileDone(lp_player, "${commander}", lp_scenarioKind, ${rows.length});`);
    lines.push("    return true;");
    lines.push("}");
    lines.push("");
  }

  lines.push(...renderDispatcher(suffix, commanders, "lp_scenarioKind"));
  return finishGalaxy(lines);
}

function renderDispatcher(suffix, commanders, scenarioArg) {
  const runnerName = suffix === "Buildings" ? "RunCommanderBuildings" : `RunCommander${suffix}`;
  const lines = [
    `bool libE0EAE146_gf_XMTestBench_${runnerName} (int lp_player, string lp_commander, string ${suffix === "Buildings" ? "lp_rosterKind" : "lp_scenarioKind"}) {`,
  ];
  for (const commander of commanders) {
    lines.push(`    if ((lp_commander == "${runtimeCommander(commander)}") && libE0EAE146_gf_XMTestBench_${functionCommander(commander)}${suffix}(lp_player, ${scenarioArg})) {`);
    lines.push("        return true;");
    lines.push("    }");
  }
  lines.push("    return false;");
  lines.push("}");
  return lines;
}

function generatedOutputs() {
  const commanders = commanderNames();
  return new Map([
    [outputFiles.rosters, renderRosterFile(commanders)],
    [outputFiles.buildings, renderBuildingsFile(commanders)],
    [outputFiles.tech, renderTechFile(commanders)],
    [outputFiles.heroAbilities, renderAbilityFile(commanders, "Hero")],
    [outputFiles.unitAbilities, renderAbilityFile(commanders, "Unit")],
  ]);
}

function main() {
  const args = parseArgs();
  if (!args.check && !args.write) {
    console.error("Usage: node scripts/sc2/generate-xmfinal-commander-profiles.mjs --check|--write");
    process.exitCode = 2;
    return;
  }

  let changed = 0;
  for (const [fileName, content] of generatedOutputs()) {
    const target = path.join(xmfinalRoot, fileName);
    const current = fs.existsSync(target) ? readText(target) : "";
    if (current !== content) {
      changed += 1;
      console.log(`PROFILE_GENERATOR_DIFF\t${fileName}`);
      if (args.write) {
        fs.writeFileSync(target, content, "utf8");
      }
    } else {
      console.log(`PROFILE_GENERATOR_OK\t${fileName}`);
    }
  }

  if (args.check && changed > 0) {
    process.exitCode = 1;
  }
}

main();
