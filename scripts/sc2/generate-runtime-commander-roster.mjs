function parseArgs(argv) {
  const options = {
    ...defaults,
    commanders: null,
    check: false,
    write: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = () => {
      index += 1;
      if (index >= argv.length) {
        throw new Error(`Missing value for ${arg}`);
      }
      return argv[index];
    };

    if (arg === "--official-root") {
      options.officialRoot = path.resolve(next());
    } else if (arg === "--mod-root") {
      options.modRoot = path.resolve(next());
      if (options.targetUserData === defaults.targetUserData) {
        options.targetUserData = path.join(
          options.modRoot,
          "Mods",
          "XM",
          "XMFinal.SC2Mod",
          "Base.SC2Data",
          "GameData",
          "UserData.xml",
        );
      }
    } else if (arg === "--target-userdata") {
      options.targetUserData = path.resolve(next());
    } else if (arg === "--output-dir") {
      options.outputDir = path.resolve(next());
    } else if (arg === "--commanders") {
      options.commanders = next()
        .split(",")
        .map((value) => value.trim())
        .filter(Boolean);
    } else if (arg === "--check") {
      options.check = true;
    } else if (arg === "--write") {
      options.write = true;
    } else if (arg === "--help" || arg === "-h") {
      printHelp();
      process.exit(0);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  if (!options.check && !options.write) {
    options.check = true;
  }

  return options;
}

