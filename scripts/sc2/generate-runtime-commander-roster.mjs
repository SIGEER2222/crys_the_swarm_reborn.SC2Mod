function assertDirectory(dir, label) {
  if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) {
    throw new Error(`${label} not found: ${dir}`);
  }
}

function readText(file) {
  return fs.readFileSync(file, "utf8");
}

function readJson(file) {
  if (!fs.existsSync(file)) {
    return [];
  }
  const raw = readText(file).trim();
  return raw ? JSON.parse(raw) : [];
}

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) {
    return files;
  }
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath, files);
    } else {
      files.push(fullPath);
    }
  }
  return files;
}

function commanderNames(officialRoot, selected) {
  const available = fs
    .readdirSync(officialRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  if (!selected) {
    return available;
  }
  const known = new Set(available);
  for (const commander of selected) {
    if (!known.has(commander)) {
      throw new Error(`Unknown commander: ${commander}`);
    }
  }
  return selected;
}

function stripXmlComments(text) {
  return text.replace(/<!--[\s\S]*?-->/g, "");
}

function xmlEscape(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function toPosix(relativePath) {
  return relativePath.split(path.sep).join("/");
}

function runtimeCommander(commander) {
  return runtimeCommanderOverrides[commander] ?? commander;
}

function commanderModule(commander) {
  return moduleOverrides[commander] ?? `XM${commander}.SC2Mod`;
}

function primaryModules(commander) {
  return new Set([commanderModule(commander), "XMCore.SC2Mod", "XMFinal.SC2Mod"]);
}

function loadUnitCatalog(modRoot) {
  const xmRoot = path.join(modRoot, "Mods", "XM");
  assertDirectory(xmRoot, "XM mod directory");
  const catalog = new Map();

  for (const file of walk(xmRoot)) {
    if (!file.toLowerCase().endsWith(".xml")) {
      continue;
    }
    const normalized = toPosix(path.relative(xmRoot, file));
    if (!normalized.toLowerCase().includes("/gamedata/")) {
      continue;
    }
    const moduleName = normalized.split("/")[0];
    const text = stripXmlComments(readText(file));
    for (const match of text.matchAll(/<CUnit\b[^>]*\bid="([^"]+)"/g)) {
      const id = match[1];
      if (!catalog.has(id)) {
        catalog.set(id, []);
      }
      catalog.get(id).push({
        module: moduleName,
        file: normalized,
      });
    }
  }

  return catalog;
}

function loadCommanderRows(officialRoot, commander) {
  const dir = path.join(officialRoot, commander);
  const sources = [
    ["hero", "heroes.json"],
    ["unit", "units.json"],
    ["building", "buildings.json"],
  ];
  const rows = [];
  const seen = new Set();

  for (const [kind, fileName] of sources) {
    for (const entry of readJson(path.join(dir, fileName))) {
      const officialId = String(entry?.unit_id ?? "").trim();
      if (!officialId) {
        continue;
      }
      const key = `${kind}|${officialId}`;
      if (seen.has(key)) {
        continue;
      }
      seen.add(key);
      rows.push({
        kind,
        officialId,
        resolvedIds: unique(asArray(entry?.resolved_unit_ids).map(String)),
        name: entry?.name ?? "",
      });
    }
  }

  return rows;
}

function asArray(value) {
  if (value == null) {
    return [];
  }
  return Array.isArray(value) ? value : [value];
}

function unique(values) {
  const result = [];
  const seen = new Set();
  for (const value of values) {
    const text = String(value ?? "").trim();
    if (text && !seen.has(text)) {
      seen.add(text);
      result.push(text);
    }
  }
  return result;
}

function addCandidate(candidates, id, reason) {
  if (!id) {
    return;
  }
  if (!candidates.some((candidate) => candidate.id === id)) {
    candidates.push({ id, reason });
  }
}

function candidateIds(commander, row) {
  const candidates = [];
  const runtime = runtimeCommander(commander);
  const ids = unique([row.officialId, ...row.resolvedIds]);

  addCandidate(candidates, row.officialId, "official");
  for (const id of row.resolvedIds) {
    if (id !== row.officialId) {
      addCandidate(candidates, id, "resolved");
    }
  }
  for (const sourceId of ids) {
    for (const alias of manualAliases[commander]?.[sourceId] ?? []) {
      addCandidate(candidates, alias, "manual-alias");
    }
  }
  for (const sourceId of ids) {
    if (sourceId.endsWith("MP")) {
      addCandidate(candidates, sourceId.slice(0, -2), "mp-strip");
    }
    if (sourceId.startsWith("HH")) {
      addCandidate(candidates, `${sourceId.slice(2)}${runtime}`, "hh-runtime-suffix");
    }
    addCandidate(candidates, `${sourceId}${runtime}`, "runtime-suffix");
  }

  return candidates;
}

function resolveRuntimeUnit(catalog, commander, row) {
  const primary = primaryModules(commander);
  const candidates = candidateIds(commander, row);
  let external = null;

  for (const candidate of candidates) {
    const hits = catalog.get(candidate.id) ?? [];
    const primaryHits = hits.filter((hit) => primary.has(hit.module));
    if (primaryHits.length > 0) {
      return {
        officialId: row.officialId,
        runtimeId: candidate.id,
        runtimeUnit: candidate.id,
        kind: row.kind,
        status: statusForCandidate(candidate),
        sourceModule: unique(primaryHits.map((hit) => hit.module)).join(","),
        sourceFile: primaryHits[0].file,
        note: candidate.reason === "official" ? "" : candidate.reason,
      };
    }
    if (!external && hits.length > 0) {
      external = {
        candidate,
        hits,
      };
    }
  }

  if (external) {
    return {
      officialId: row.officialId,
      runtimeId: external.candidate.id,
      runtimeUnit: "",
      kind: row.kind,
      status: "external-only",
      sourceModule: unique(external.hits.map((hit) => hit.module)).join(","),
      sourceFile: external.hits[0].file,
      note: "catalog exists outside commander/shared modules; review before using in runtime factories",
    };
  }

  return {
    officialId: row.officialId,
    runtimeId: "",
    runtimeUnit: "",
    kind: row.kind,
    status: "unresolved",
    sourceModule: "",
    sourceFile: "",
    note: "no CUnit catalog match in target mod scan",
  };
}

function statusForCandidate(candidate) {
  if (candidate.reason === "official") {
    return "exact";
  }
  if (candidate.reason === "resolved") {
    return "resolved";
  }
  return "alias";
}

function buildRoster(options) {
  const catalog = loadUnitCatalog(options.modRoot);
  const commanders = commanderNames(options.officialRoot, options.commanders);
  const results = [];

  for (const commander of commanders) {
    const rows = loadCommanderRows(options.officialRoot, commander);
    if (rows.length > maxRosterEntries) {
      throw new Error(`${commander} roster has ${rows.length} entries; max is ${maxRosterEntries}`);
    }
    const entries = rows.map((row) => resolveRuntimeUnit(catalog, commander, row));
    results.push({
      commander,
      runtimeCommander: runtimeCommander(commander),
      module: commanderModule(commander),
      count: entries.length,
      entries,
      statusCounts: countBy(entries, (entry) => entry.status),
    });
  }

  return {
    metadata: {
      generatedAt: new Date().toISOString(),
      generatedBy,
      officialRoot: options.officialRoot,
      modRoot: options.modRoot,
      targetUserData: options.targetUserData,
      rosterUserId,
      maxRosterEntries,
    },
    commanders: results,
  };
}

function countBy(items, selector) {
  const counts = {};
  for (const item of items) {
    const key = selector(item);
    counts[key] = (counts[key] ?? 0) + 1;
  }
  return counts;
}

function renderUserData(roster) {
  const lines = [
    `    <!-- ${generatedMarker}. Do not edit this CUser manually. -->`,
    `    <CUser id="${rosterUserId}">`,
    '        <Fields Id="OfficialCommander" Type="String"/>',
    '        <Fields Id="RuntimeCommander" Type="String"/>',
    '        <Fields Id="RuntimeModule" Type="String"/>',
    '        <Fields Id="Count" Type="Int"/>',
    '        <Fields Id="OfficialId" Type="String" Count="96"/>',
    '        <Fields Id="RuntimeUnit" Type="Unit" Count="96"/>',
    '        <Fields Id="Kind" Type="String" Count="96"/>',
    '        <Fields Id="Status" Type="String" Count="96"/>',
    '        <Instances Id="[Default]"/>',
  ];

  for (const commander of roster.commanders) {
    lines.push(`        <Instances Id="${xmlEscape(commander.runtimeCommander)}">`);
    appendString(lines, "OfficialCommander", commander.commander, 12);
    appendString(lines, "RuntimeCommander", commander.runtimeCommander, 12);
    appendString(lines, "RuntimeModule", commander.module, 12);
    appendInt(lines, "Count", commander.entries.length, 12);
    commander.entries.forEach((entry, index) => {
      appendString(lines, "OfficialId", entry.officialId, 12, index);
      if (entry.runtimeUnit) {
        appendUnit(lines, "RuntimeUnit", entry.runtimeUnit, 12, index);
      }
      appendString(lines, "Kind", entry.kind, 12, index);
      appendString(lines, "Status", entry.status, 12, index);
    });
    lines.push("        </Instances>");
  }

  lines.push("    </CUser>");
  return `${lines.join("\r\n")}\r\n`;
}

function appendString(lines, field, value, indent, index = null) {
  lines.push(`${" ".repeat(indent)}<String String="${xmlEscape(value)}">${fieldNode(field, index)}</String>`);
}

function appendInt(lines, field, value, indent, index = null) {
  lines.push(`${" ".repeat(indent)}<Int Int="${Number(value)}">${fieldNode(field, index)}</Int>`);
}

function appendUnit(lines, field, value, indent, index = null) {
  lines.push(`${" ".repeat(indent)}<Unit Unit="${xmlEscape(value)}">${fieldNode(field, index)}</Unit>`);
}

function fieldNode(field, index) {
  const indexText = index == null || index === 0 ? "" : ` Index="${index}"`;
  return `<Field Id="${field}"${indexText}/>`;
}

function upsertUserDataXml(existingText, rosterUserData) {
  const baseText = existingText?.trim()
    ? existingText
    : '<?xml version="1.0" encoding="utf-8"?>\r\n<Catalog>\r\n</Catalog>\r\n';
  const pattern = new RegExp(
    `\\s*<!-- ${escapeRegex(generatedMarker)}\\. Do not edit this CUser manually\\. -->\\s*<CUser\\s+id="${rosterUserId}"[\\s\\S]*?</CUser>`,
  );
  if (pattern.test(baseText)) {
    return ensureTrailingNewline(baseText.replace(pattern, `\r\n${rosterUserData.trimEnd()}`));
  }
  const closingIndex = baseText.lastIndexOf("</Catalog>");
  if (closingIndex < 0) {
    throw new Error("Target UserData.xml does not contain </Catalog>");
  }
  const before = baseText.slice(0, closingIndex).replace(/\s*$/u, "\r\n");
  const after = baseText.slice(closingIndex);
  return ensureTrailingNewline(`${before}${rosterUserData}${after}`);
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function ensureTrailingNewline(value) {
  return value.endsWith("\n") ? value : `${value}\r\n`;
}

function renderMarkdown(roster) {
  const lines = [
    "# 合作指挥官版起义狂潮 runtime roster 映射",
    "",
    `- 生成时间：${new Date(roster.metadata.generatedAt).toLocaleString("zh-CN", { hour12: false })}`,
    `- 生成脚本：\`${generatedBy}\``,
    `- 目标 Mod：\`${roster.metadata.modRoot}\``,
    `- 目标 UserData：\`${roster.metadata.targetUserData}\``,
    "- 口径：只读取官方 `heroes.json` / `units.json` / `buildings.json`，不把 command card 的单位/建筑噪声当 roster。",
    "- `exact/resolved/alias` 可作为运行时工厂候选；`external-only/unresolved` 需要人工确认后再接初始化器或测试台。",
    "",
    "## 汇总",
    "",
    "| 指挥官 | 运行时 | 模块 | 总数 | exact | resolved | alias | external-only | unresolved |",
    "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
  ];

  for (const commander of roster.commanders) {
    const counts = commander.statusCounts;
    lines.push(
      `| ${commander.commander} | ${commander.runtimeCommander} | \`${commander.module}\` | ${commander.count} | ${counts.exact ?? 0} | ${counts.resolved ?? 0} | ${counts.alias ?? 0} | ${counts["external-only"] ?? 0} | ${counts.unresolved ?? 0} |`,
    );
  }

  for (const commander of roster.commanders) {
    const interesting = commander.entries.filter((entry) => entry.status !== "exact");
    lines.push("", `## ${commander.commander}`, "");
    lines.push(`- 运行时实例：\`${commander.runtimeCommander}\``);
    lines.push(`- 模块：\`${commander.module}\``);
    if (interesting.length === 0) {
      lines.push("- 非精确映射：无");
      continue;
    }
    lines.push("", "| 类型 | 官方 ID | Runtime ID | 状态 | 来源模块 | 备注 |");
    lines.push("| --- | --- | --- | --- | --- | --- |");
    for (const entry of interesting) {
      lines.push(
        `| ${entry.kind} | \`${entry.officialId}\` | ${entry.runtimeId ? `\`${entry.runtimeId}\`` : ""} | ${entry.status} | ${entry.sourceModule ? `\`${entry.sourceModule}\`` : ""} | ${entry.note} |`,
      );
    }
  }

  lines.push("");
  return `${lines.join("\n")}\n`;
}

function writeOutputs(roster, options, nextUserData) {
  fs.mkdirSync(path.dirname(options.targetUserData), { recursive: true });
  fs.writeFileSync(options.targetUserData, nextUserData, "utf8");
  fs.mkdirSync(options.outputDir, { recursive: true });
  fs.writeFileSync(
    path.join(options.outputDir, "commander-runtime-roster.json"),
    `${JSON.stringify(roster, null, 2)}\n`,
    "utf8",
  );
  fs.writeFileSync(
    path.join(options.outputDir, "commander-runtime-roster.md"),
    renderMarkdown(roster),
    "utf8",
  );
}

function printSummary(roster) {
  for (const commander of roster.commanders) {
    const counts = commander.statusCounts;
    console.log(
      [
        commander.commander,
        `total=${commander.count}`,
        `exact=${counts.exact ?? 0}`,
        `resolved=${counts.resolved ?? 0}`,
        `alias=${counts.alias ?? 0}`,
        `external-only=${counts["external-only"] ?? 0}`,
        `unresolved=${counts.unresolved ?? 0}`,
      ].join(" "),
    );
  }
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  assertDirectory(options.officialRoot, "Official commanders root");
  assertDirectory(options.modRoot, "Target mod root");

  const roster = buildRoster(options);
  const existing = fs.existsSync(options.targetUserData) ? readText(options.targetUserData) : "";
  const nextUserData = upsertUserDataXml(existing, renderUserData(roster));

  printSummary(roster);

  if (options.check) {
    if (existing && existing !== nextUserData) {
      console.error(`STALE ${options.targetUserData}`);
      process.exitCode = 1;
    } else if (!existing) {
      console.error(`MISSING ${options.targetUserData}`);
      process.exitCode = 1;
    }
  }

  if (options.write) {
    writeOutputs(roster, options, nextUserData);
    console.log(`WROTE ${options.targetUserData}`);
    console.log(`WROTE ${path.join(options.outputDir, "commander-runtime-roster.json")}`);
    console.log(`WROTE ${path.join(options.outputDir, "commander-runtime-roster.md")}`);
  }
}

main();
